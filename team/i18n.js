export const DICT = { es, en };

/** t(key, vars): the sentence in one language. Numbers are written the way that language writes them. */
export function makeT(lang) {
  const dict = DICT[lang] || DICT.es, locale = LOCALE[lang] || LOCALE.es;
  const show = (v) => (typeof v === 'number' ? v.toLocaleString(locale) : String(v));
  return function t(key, vars = {}) {
    let text = dict[key];
    if (text === undefined) throw new Error(`i18n: missing key ${key}`);
    if (Array.isArray(text)) text = text[vars.n === 1 ? 0 : 1];
    return text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? show(vars[name]) : m));
  };
}
